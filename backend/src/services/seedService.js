// Helper to generate dates relative to today
const getRelativeDate = (daysOffset) => {
  const date = new Date();
  date.setDate(date.getDate() + daysOffset);
  // Set to end of day for clear expiry
  date.setHours(23, 59, 59, 999);
  return date;
};

